import { readFileSync, writeFileSync, existsSync, mkdirSync, cpSync, mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import assert from 'node:assert/strict';
const dest=mkdtempSync(path.join(tmpdir(),'asset-studio-setup-'));
for(const f of ['setup.mjs','brand.mjs','generate.mjs','studio.config.json','templates']) cpSync(f,path.join(dest,f),{recursive:true});
const run=(file,input)=>spawnSync(process.execPath,[file,...(input?.startsWith('{')?['--paste']:[])],{cwd:dest,input,encoding:'utf8'});
const initial=readFileSync(path.join(dest,'studio.config.json'),'utf8');
const base=JSON.parse(initial);
const answers=['QA Studio','@qa','1',...base.media.flatMap(m=>['y','qa-category']),'n'];
let r=run('setup.mjs',answers.join('\n')+'\n');assert.equal(r.status,0,r.stderr);
assert.equal(JSON.parse(readFileSync(path.join(dest,'studio.config.json'))).hideStarters,true);
assert(existsSync(path.join(dest,'templates/statics/posters/starter-poster.html')));
r=run('generate.mjs');assert.equal(r.status,0,r.stderr);
assert(!JSON.parse(readFileSync(path.join(dest,'build/manifest.json'))).templates.some(t=>t.name.startsWith('starter-')));
const payload={media:[{id:'statics',kind:'still',categories:['new-category']}]};
const beforeDefaults=JSON.parse(readFileSync(path.join(dest,'studio.config.json')));
beforeDefaults.brand.accent='#123456'; beforeDefaults.brand.accentSoft='#abcdef';
writeFileSync(path.join(dest,'studio.config.json'),JSON.stringify(beforeDefaults));
r=run('setup.mjs','\n');assert.equal(r.status,0,r.stderr);
const afterDefaults=JSON.parse(readFileSync(path.join(dest,'studio.config.json')));
assert.deepEqual(afterDefaults.brand,beforeDefaults.brand);
assert.equal(afterDefaults.hideStarters,true);
r=run('setup.mjs',['','','','','','','','n',''].join('\n')+'\n');assert.equal(r.status,0,r.stderr);
assert(!JSON.parse(readFileSync(path.join(dest,'studio.config.json'))).media.some(m=>m.id==='video'));
r=run('setup.mjs',['','','','','','','','y','',''].join('\n')+'\n');assert.equal(r.status,0,r.stderr);
assert(JSON.parse(readFileSync(path.join(dest,'studio.config.json'))).media.some(m=>m.id==='video'));
console.log('PASS Enter preserves brand, accent, accentSoft and hidden starters; excluded Video can be re-enabled');
r=run('setup.mjs',JSON.stringify(payload)+'\nEND\n');assert.equal(r.status,0,r.stderr);
const cfg=JSON.parse(readFileSync(path.join(dest,'studio.config.json')));
assert.equal(cfg.media[0].dir,'statics');assert.equal(cfg.hideStarters,true);
assert(existsSync(path.join(dest,'templates/statics/new-category/poster.html')));
const saved=readFileSync(path.join(dest,'studio.config.json'),'utf8');
r=run('setup.mjs',JSON.stringify({media:[{id:'../escape',kind:'still'}]})+'\nEND\n');
assert.notEqual(r.status,0);assert.equal(readFileSync(path.join(dest,'studio.config.json'),'utf8'),saved);
console.log('PASS no-starters preserves originals; repeat setup seeds new category; omitted dir defaults to id; invalid input does not overwrite config');
console.log('QA fixture: '+dest);
