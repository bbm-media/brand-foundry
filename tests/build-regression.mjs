import { readFileSync, writeFileSync, mkdtempSync, cpSync, rmSync, readdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
import assert from 'node:assert/strict';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const fixture=mkdtempSync(path.join(tmpdir(),'asset-studio-build-'));
for(const file of ['generate.mjs','brand.mjs','studio.config.json','templates']) cpSync(path.join(root,file),path.join(fixture,file),{recursive:true});
const build=()=>spawnSync(process.execPath,['generate.mjs'],{cwd:fixture,encoding:'utf8'});
assert.equal(build().status,0);
const before=readFileSync(path.join(fixture,'build/manifest.json'));
const broken=path.join(fixture,'templates/statics/posters/broken.html');
writeFileSync(broken,"<html data-composition-variables='[{bad}]'></html>");
assert.notEqual(build().status,0);
assert.deepEqual(readFileSync(path.join(fixture,'build/manifest.json')),before);
assert(!readdirSync(fixture).some(file=>file.startsWith('.build-stage-')));
rmSync(broken);
assert.equal(build().status,0);
assert(!readdirSync(fixture).some(file=>file.startsWith('.build-')));
console.log('PASS failed build preserves the last working manifest; recovery succeeds; temporary builds cleaned');
